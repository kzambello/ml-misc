# st.set_page_config(page_title="Anomaly Detection")
st.set_page_config(
    page_title="Anomaly Detection",
    layout="wide",
)

st.title("Anomaly Detection")

lambda_url = os.getenv("LAMBDA_URL")

if not lambda_url:
    lambda_url = st.text_input(
        "API endpoint",
        placeholder="https://id.execute-api.region.amazonaws.com/predict",
    )

st.caption(
    "Enter one transaction per row, with 30 comma-separated values. "
    "Do not include the column names."
)

# example = ",".join(["0"] * 30)
example = ",".join(FEATURES)

if "transaction_input" not in st.session_state:
    st.session_state["transaction_input"] = ""

col1, col2, col3 = st.columns(3)

with col1:
    if st.button("Load 10-row anomaly example", use_container_width=True):
        st.session_state["transaction_input"] = EXAMPLE_ROWS_FRAUD

with col2:
    if st.button("Load 10-row normal example", use_container_width=True):
        st.session_state["transaction_input"] = EXAMPLE_ROWS_NORMAL

with col3:
    if st.button("Clear", use_container_width=True):
        st.session_state["transaction_input"] = ""

raw_input = st.text_area(
    "Transaction features",
    height=220,
    key="transaction_input",
    placeholder=example,
)

if st.button("Analyze transactions", type="primary"):
    if not lambda_url:
        st.error("Enter API endpoint.")
        st.stop()

    if not raw_input.strip():
        st.error("Enter at least one transaction.")
        st.stop()

    transactions = []
    errors = []

    lines = [line.strip() for line in raw_input.strip().splitlines() if line.strip()]

    for line_number, line in enumerate(lines, start=1):
        values = [value.strip() for value in line.split(",")]

        if len(values) != len(FEATURES):
            errors.append(
                f"Row {line_number}: expected 30 values, found {len(values)}."
            )
            continue

        try:
            numeric_values = [float(value) for value in values]
        except ValueError:
            errors.append(f"Row {line_number}: every value must be numeric.")
            continue

        transaction = dict(zip(FEATURES, numeric_values))

        # Lambda expects Time to be usable with int(...)
        transaction["Time"] = int(transaction["Time"])

        transactions.append(transaction)

    if errors:
        st.error("Input validation failed:")
        for error in errors:
            st.write(f"- {error}")
        st.stop()

    payload = {"transactions": transactions}

    try:
        response = requests.post(
            lambda_url,
            json=payload,
            timeout=60,
        )
        response.raise_for_status()

        result = response.json()

        if "body" in result:
            body = result["body"]
            result = json.loads(body) if isinstance(body, str) else body

        predictions = result["predictions"]
        mse_values = result["mse"]
        threshold = float(result["threshold"])

        results = pd.DataFrame(transactions)
        results["mse"] = mse_values
        results["prediction"] = predictions
        results["classification"] = results["prediction"].map(
            {
                0: "Normal",
                1: "Anomaly",
            }
        )

        st.success("Analysis complete.")
        st.metric("Transactions analyzed", len(results))
        st.metric("Detected anomalies", int(sum(predictions)))
        st.metric("Threshold", f"{threshold:.6f}")

        st.dataframe(results, use_container_width=True)

        st.download_button(
            "Download results",
            data=results.to_csv(index=False),
            file_name="transaction_predictions.csv",
            mime="text/csv",
        )

    except requests.exceptions.RequestException as error:
        st.error(f"Could not call Lambda: {error}")

    except (KeyError, ValueError, json.JSONDecodeError) as error:
        st.error(f"Unexpected Lambda response: {error}")
